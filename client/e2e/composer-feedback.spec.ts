test('transcription preserves newer typing and requires explicit insertion; Cancel ignores later data', async ({ page }) => {
  await login(page)
  await control(page, { delayTranscription: true })
  await recording(page).setInputFiles(audioFile)
  await expect(page.getByText('Transcribing audio…', { exact: true })).toBeVisible()
  await expect.poll(() => count(page, '/api/audio/transcribe')).toBe(1)
  await page.getByLabel('Message Hermes').fill('newer text')
  await control(page, { delayTranscription: false })
  await expect(page.getByText('Your draft changed. The transcript was not inserted.')).toBeVisible()
  await expect(page.getByLabel('Message Hermes')).toHaveValue('newer text')
  await page.getByRole('button', { name: 'Insert transcript' }).click()
  await expect(page.getByLabel('Message Hermes')).toHaveValue('newer text\nFixture spoken words')
  await control(page, { delayTranscription: true })
  await recording(page).setInputFiles(audioFile)
  await expect.poll(() => count(page, '/api/audio/transcribe')).toBe(2)
  await page.getByRole('button', { name: 'Cancel transcription' }).click()
  await expect(page.getByText('Transcribing audio…', { exact: true })).toHaveCount(0)
  await control(page, { delayTranscription: false })
  await expect(page.getByLabel('Message Hermes')).toHaveValue('newer text\nFixture spoken words')
})

test('Queue and Stop remain independent, acceptance is not execution, and uncertainty preserves recovery', async ({ page }, testInfo) => {
  await login(page)
  await control(page, { holdTurn: true })
  await page.getByLabel('Message Hermes').fill('start active turn')
  await page.getByRole('button', { name: 'Send', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Queue', exact: true })).toBeVisible()
  await expect(page.getByText('Gateway accepted your message.', { exact: true })).toBeVisible()
  await control(page, { delaySubmission: true, delayInterrupt: true })
  await page.getByLabel('Message Hermes').fill('next task')
  await page.getByRole('button', { name: 'Queue', exact: true }).click()
  await page.getByRole('button', { name: 'Stop Hermes' }).click()
  await expect(page.getByRole('button', { name: 'Stop Hermes' })).toBeDisabled()
  await expect.poll(() => count(page, 'prompt.submit')).toBe(2)
  await expect.poll(() => count(page, 'session.interrupt')).toBe(1)
  await expect(page.getByText('Message submission pending', { exact: true })).toHaveCount(0)
  await page.getByLabel('Message Hermes').fill('following draft')
  await control(page, { delaySubmission: false })
  await expect(page.getByText('Gateway accepted your queued prompt. Execution has not been confirmed.')).toBeVisible()
  await expect(page.getByLabel('Message Hermes')).toHaveValue('following draft')
  await control(page, { delayInterrupt: false })
  await expect(page.getByText('Stop requested. Queued prompts may still run.')).toBeVisible()
  await expect(page.getByRole('button', { name: 'Queue', exact: true })).toBeEnabled()
  await page.screenshot({ path: testInfo.outputPath('queue-and-stop.png') })
  await page.getByLabel('Message Hermes').fill('draft uncertain response')
  await page.getByRole('button', { name: 'Queue', exact: true }).click()
  await expect(page.getByText('Delivery not confirmed. Check the conversation before sending again.').first()).toBeVisible()
  expect(await count(page, 'prompt.submit')).toBe(3)
  await control(page, { rejectInterrupt: true })
  await page.getByRole('button', { name: 'Stop Hermes' }).click()
  await expect(page.getByRole('alert').filter({ hasText: 'Stop was not confirmed' })).toBeVisible()
})

