import { expect, test, type Page } from '@playwright/test'

async function login(page: Page) {
  await page.goto('/')
  await page.getByRole('button', { name: 'Continue' }).click()
  await page.getByRole('button', { name: 'Use password for Test account' }).click()
  await page.getByPlaceholder('Username').fill('composer-user')
  await page.getByPlaceholder('Password').fill('fixture-password')
  await page.getByRole('button', { name: 'Sign in', exact: true }).click()
  await page.getByRole('button', { name: 'Hermes', exact: true }).click()
  await expect(page.getByText('Durable reply from saved-default', { exact: true })).toBeVisible()
}
async function control(page: Page, update: Record<string, boolean>) {
  await page.evaluate(async update => { await fetch('/api/fixture-control', { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify(update) }) }, update)
}
async function count(page: Page, method: string) {
  return page.evaluate(async method => {
    const { calls } = await (await fetch('/api/fixture-calls')).json()
    return calls.filter((call: { method: string; path?: string }) => call.method === method || call.path === method).length as number
  }, method)
}
const files = (page: Page) => page.locator('input[type="file"][multiple]')
const recording = (page: Page) => page.locator('input[type="file"][capture]')
const textFile = (name: string) => ({ name, mimeType: 'text/plain', buffer: Buffer.from('fixture file') })
const audioFile = { name: 'voice.wav', mimeType: 'audio/wav', buffer: Buffer.from('fixture audio') }

test('uploads have file states; removal retires a pending result and failures preserve successful files', async ({ page }, testInfo) => {
  await login(page)
  await control(page, { delayAttachments: true })
  await files(page).setInputFiles([textFile('one.txt'), textFile('rejected.txt'), textFile('three.txt')])
  await expect(page.getByRole('status').filter({ hasText: 'Uploading attachments' })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Send', exact: true })).toBeDisabled()
  await page.getByRole('button', { name: 'Remove attachment one.txt', exact: true }).click()
  await control(page, { delayAttachments: false })
  await expect(page.getByText('one.txt', { exact: true })).toHaveCount(0)
  await expect(page.locator('.composer-file').filter({ hasText: 'rejected.txt' })).toContainText('Failed')
  await expect(page.locator('.composer-file').filter({ hasText: 'three.txt' })).toContainText('Ready')
  await page.getByLabel('Message Hermes').fill('text kept during upload')
  await page.screenshot({ path: testInfo.outputPath('attachment-failure.png') })
  await page.getByRole('button', { name: 'Remove attachment rejected.txt', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Send', exact: true })).toBeEnabled()
  await expect(page.getByLabel('Message Hermes')).toHaveValue('text kept during upload')
})

