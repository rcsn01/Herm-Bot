test('Cancel and Escape are inert, and keyboard confirmation restores focus', async ({ page }) => {
  await login(page)
  await page.getByLabel('Message Hermes').fill('Do not discard')
  await privacy(page)
  const before = await keys(page, 'hermes.drafts.v1:')
  const button = page.getByRole('button', { name: 'Clear local data', exact: true })
  await button.focus()
  await page.keyboard.press('Enter')
  await expect(page.getByRole('alertdialog').getByRole('button', { name: 'Cancel' })).toBeFocused()
  await page.keyboard.press('Escape')
  await expect(button).toBeFocused()
  expect(await keys(page, 'hermes.drafts.v1:')).toEqual(before)
  await button.click()
  await page.getByRole('alertdialog').getByRole('button', { name: 'Cancel' }).click()
  expect(await keys(page, 'hermes.drafts.v1:')).toEqual(before)
})

test('retries failed history removal without turning history saving back on', async ({ page }) => {
  await login(page)
  await privacy(page)
  await page.evaluate(() => {
    const original = Storage.prototype.removeItem
    Object.assign(window, { restorePrivacyStorage: () => { Storage.prototype.removeItem = original } })
    Storage.prototype.removeItem = function (key) { if (key.startsWith('hermes.transcript.')) throw new DOMException('Blocked', 'SecurityError'); return original.call(this, key) }
  })
  await page.getByRole('switch').click()
  await page.getByRole('button', { name: 'Turn off and remove saved history' }).click()
  await expect(page.getByRole('switch')).toHaveAttribute('aria-checked', 'false')
  await expect(page.getByRole('button', { name: 'Retry history removal' })).toBeVisible()
  expect((await keys(page, 'hermes.transcript.v2:')).length).toBeGreaterThan(0)
  await page.evaluate(() => (window as unknown as { restorePrivacyStorage(): void }).restorePrivacyStorage())
  await page.getByRole('button', { name: 'Retry history removal' }).click()
  await expect(page.getByRole('switch')).toHaveAttribute('aria-checked', 'false')
  await expect(page.getByRole('button', { name: 'Retry history removal' })).toHaveCount(0)
  expect(await keys(page, 'hermes.transcript.')).toEqual([])
})

test('reports partial removal failure and supports retry without silently losing the warning', async ({ page }) => {
  await login(page)
  await page.getByLabel('Message Hermes').fill('Sensitive unfinished draft')
  await privacy(page)
  await page.evaluate(() => {
    const original = Storage.prototype.removeItem
    Object.assign(window, { restorePrivacyStorage: () => { Storage.prototype.removeItem = original } })
    Storage.prototype.removeItem = function (key) { if (key.startsWith('hermes.drafts.v1:')) throw new DOMException('Blocked', 'SecurityError'); return original.call(this, key) }
  })
  await clear(page)
  await expect(page.getByRole('alert')).toContainText('Draft and recovery removal could not be confirmed')
  expect((await keys(page, 'hermes.drafts.v1:')).length).toBeGreaterThan(0)
  await page.evaluate(() => (window as unknown as { restorePrivacyStorage(): void }).restorePrivacyStorage())
  await clear(page)
  await expect(page.getByRole('status').filter({ hasText: 'Privacy change completed' })).toBeVisible()
  expect(await keys(page, 'hermes.drafts.v1:')).toEqual([])
})
