import { expect, test, type Page } from '@playwright/test'

async function login(page: Page) {
  await page.goto('/')
  await page.getByRole('button', { name: 'Continue' }).click()
  await page.getByRole('button', { name: 'Use password for Test account' }).click()
  await page.getByPlaceholder('Username').fill('privacy-user')
  await page.getByPlaceholder('Password').fill('fixture-password')
  await page.getByRole('button', { name: 'Sign in', exact: true }).click()
  await page.getByRole('button', { name: 'Hermes', exact: true }).click()
  await expect(page.getByText('Durable reply from saved-default', { exact: true })).toBeVisible()
}
async function privacy(page: Page) {
  await page.getByRole('button', { name: 'Back to bots' }).click()
  await page.getByRole('button', { name: 'Open settings' }).click()
  await page.getByRole('button', { name: /^Privacy / }).click()
  await expect(page.getByRole('heading', { name: 'Privacy', exact: true })).toBeVisible()
}
async function clear(page: Page) {
  await page.getByRole('button', { name: 'Clear local data', exact: true }).click()
  await page.getByRole('alertdialog').getByRole('button', { name: 'Clear local data', exact: true }).click()
}
async function keys(page: Page, prefix: string) { return page.evaluate(prefix => Object.keys(localStorage).filter(key => key.startsWith(prefix)), prefix) }
async function calls(page: Page) { return page.evaluate(async () => (await (await fetch('/api/fixture-calls')).json()).calls as Array<{ kind: string; method: string; path?: string }>) }

test('history off survives reload, keeps drafts, and re-enables only future synchronization', async ({ page }, testInfo) => {
  await login(page)
  await page.getByLabel('Message Hermes').fill('Draft survives history opt-out')
  await privacy(page)
  const toggle = page.getByRole('switch', { name: 'Save conversation history on this device' })
  await expect(toggle).toHaveAttribute('aria-checked', 'true')
  await toggle.click()
  await expect(page.getByRole('alertdialog')).toContainText('ALL accounts')
  await page.getByRole('button', { name: 'Turn off and remove saved history' }).click()
  await expect(toggle).toHaveAttribute('aria-checked', 'false')
  expect(await keys(page, 'hermes.transcript.')).toEqual([])
  expect((await keys(page, 'hermes.drafts.v1:')).length).toBeGreaterThan(0)
  await page.screenshot({ path: testInfo.outputPath('privacy-history-off.png') })
  await page.reload()
  await page.getByRole('button', { name: 'Hermes', exact: true }).click()
  await expect(page.getByLabel('Message Hermes')).toHaveValue('Draft survives history opt-out')
  expect(await keys(page, 'hermes.transcript.')).toEqual([])
  await privacy(page)
  await expect(toggle).toHaveAttribute('aria-checked', 'false')
  await toggle.click()
  expect(await keys(page, 'hermes.transcript.')).toEqual([])
  await page.getByRole('button', { name: 'Back', exact: true }).last().click()
  await page.getByRole('button', { name: 'Back to bots' }).click()
  await page.getByRole('button', { name: 'Hermes', exact: true }).click()
  await expect.poll(() => keys(page, 'hermes.transcript.v2:').then(keys => keys.length)).toBeGreaterThan(0)
})

test('clears all current-account profiles offline, keeps other-account records and preferences, and does not restore automatically', async ({ page }) => {
  await login(page)
  await page.getByLabel('Message Hermes').fill('Default private draft')
  await page.getByRole('button', { name: 'Back to bots' }).click()
  await page.getByRole('button', { name: 'Work', exact: true }).click()
  await page.getByLabel('Message Hermes').fill('Work private draft')
  await page.evaluate(() => {
    const other = JSON.stringify(['https://other-gateway.test', 'other-account'])
    localStorage.setItem('hermes.drafts.v1:' + encodeURIComponent(JSON.stringify([other, null, 'foreign'])), 'foreign draft')
    localStorage.setItem('hermes.transcript.v2:' + encodeURIComponent(JSON.stringify([other, null, 'foreign'])), 'foreign history')
    localStorage.setItem('hermes.mobile.session.v2:' + encodeURIComponent(JSON.stringify([other, 'https://other-gateway.test', null])), 'foreign')
    localStorage.setItem('hermes.theme', 'dark')
    window.dispatchEvent(new Event('offline'))
  })
  await privacy(page)
  const before = await calls(page)
  await clear(page)
  await expect(page.getByRole('status').filter({ hasText: 'Privacy change completed' })).toBeVisible()
  expect(await keys(page, 'hermes.drafts.v1:')).toHaveLength(1)
  expect(await keys(page, 'hermes.transcript.v2:')).toHaveLength(1)
  expect(await keys(page, 'hermes.mobile.session.v2:')).toHaveLength(1)
  expect(await page.evaluate(() => localStorage.getItem('hermes.theme'))).toBe('dark')
  await page.evaluate(() => window.dispatchEvent(new Event('online')))
  await expect(page.getByRole('status').filter({ hasText: 'No conversation selected. Open a conversation to load history.' })).toBeVisible()
  await expect(page.getByRole('heading', { name: 'Privacy', exact: true })).toBeVisible()
  const conversationWork = (entries: Awaited<ReturnType<typeof calls>>) => entries.filter(call => /^(session\.(create|resume|history|branch)|prompt\.submit)$/.test(call.method) || call.path?.endsWith('/messages'))
  expect(conversationWork(await calls(page))).toEqual(conversationWork(before))
  expect((await calls(page)).some(call => call.path === '/auth/logout' || call.method === 'DELETE')).toBe(false)
  await page.getByRole('button', { name: 'Back', exact: true }).last().click()
  await page.getByRole('button', { name: 'Back to bots' }).click()
  await page.getByRole('button', { name: 'Work', exact: true }).click()
  await expect(page.getByLabel('Message Hermes')).toHaveValue('')
  await expect(page.getByRole('button', { name: 'Send', exact: true })).toBeDisabled()
})

test('clearing another tab retires the old composer without logout, conflicts, or repopulation', async ({ page, context }) => {
  await login(page)
  await page.getByLabel('Message Hermes').fill('Old shared private draft')
  const other = await context.newPage()
  await other.goto('/')
  await other.getByRole('button', { name: 'Hermes', exact: true }).click()
  await expect(other.getByLabel('Message Hermes')).toHaveValue('Old shared private draft')
  await privacy(page)
  await clear(page)
  await expect(other.getByLabel('Message Hermes')).toHaveValue('')
  await expect(other.getByText('Durable reply from saved-default', { exact: true })).toHaveCount(0)
  await expect(other.getByText('Another draft was preserved', { exact: true })).toHaveCount(0)
  expect(await keys(other, 'hermes.drafts.v1:')).toEqual([])
  expect(await keys(other, 'hermes.transcript.v2:')).toEqual([])
  await expect(other.getByRole('button', { name: 'Continue', exact: true })).toHaveCount(0)
  await other.getByRole('button', { name: 'Back to bots' }).click()
  await other.getByRole('button', { name: 'Hermes', exact: true }).click()
  await other.getByLabel('Message Hermes').fill('New work after clear')
  await expect.poll(() => other.evaluate(() => Object.keys(localStorage)
    .filter(key => key.startsWith('hermes.drafts.v1:'))
    .some(key => JSON.parse(localStorage.getItem(key)!).content.text === 'New work after clear'))).toBe(true)
  await expect(other.getByText('Saved on this device.', { exact: true })).toHaveCount(0)
})

