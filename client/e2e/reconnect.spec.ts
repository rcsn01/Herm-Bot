import { expect, test, type Page } from '@playwright/test'

async function login(page: Page) {
  await page.goto('/')
  await page.getByRole('button', { name: 'Continue' }).click()
  await page.getByRole('button', { name: 'Use password for Test account' }).click()
  await page.getByPlaceholder('Username').fill('reconnect-user')
  await page.getByPlaceholder('Password').fill('fixture-password')
  await page.getByRole('button', { name: 'Sign in', exact: true }).click()
  await page.getByRole('button', { name: 'Hermes', exact: true }).click()
  await expect(page.getByText('Durable reply from saved-default', { exact: true })).toBeVisible()
}
async function control(page: Page, update: Record<string, unknown>) {
  await page.evaluate(async update => {
    const response = await fetch('/api/fixture-control', { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify(update) })
    if (!response.ok) throw new Error('Fixture control failed')
  }, update)
}
async function calls(page: Page) {
  return page.evaluate(async () => (await (await fetch('/api/fixture-calls')).json()).calls as Array<{ kind: string; method: string; params?: { session_id?: string; text?: string }; profile?: string }>)
}
async function offline(page: Page) {
  await page.evaluate(() => window.dispatchEvent(new Event('offline')))
  await expect(page.getByText('Device offline. You can read saved conversations and prepare drafts.', { exact: true })).toBeVisible()
}
async function online(page: Page) { await page.evaluate(() => window.dispatchEvent(new Event('online'))) }

test('reads cached A/B across profiles, types exact drafts, and requires intentional Send after recovery', async ({ page }) => {
  await login(page)
  await control(page, { longHistorySession: 'saved-default' })
  await page.getByRole('button', { name: 'Back to bots' }).click()
  await page.getByRole('button', { name: 'Hermes', exact: true }).click()
  await expect(page.getByText(/^Saved history 30\./)).toBeVisible()
  await page.getByLabel('Message Hermes').fill('A draft')
  await page.getByRole('button', { name: 'Back to bots' }).click()
  await page.getByRole('button', { name: 'Work', exact: true }).click()
  await expect(page.getByText('Durable reply from saved-work', { exact: true })).toBeVisible()
  await offline(page)
  const before = await calls(page)
  await page.getByLabel('Message Hermes').fill('  /offline B\nexact text  ')
  await expect(page.getByLabel('Message Hermes')).toBeEditable()
  await expect(page.getByRole('button', { name: 'Send', exact: true })).toBeDisabled()
  await page.getByRole('button', { name: 'Back to bots' }).click()
  await page.getByRole('button', { name: /^Hermes Saved conversations/ }).click()
  await expect(page.getByLabel('Message Hermes')).toHaveValue('A draft')
  await expect(page.getByText('Durable reply from saved-default', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Open navigation' }).click()
  await expect(page.getByText(/Saved on this device ·/).first()).toBeVisible()
  await expect(page.getByRole('button', { name: 'New session', exact: true })).toBeDisabled()
  await page.keyboard.press('Escape')
  expect((await calls(page)).filter(call => call.kind === 'rpc')).toEqual(before.filter(call => call.kind === 'rpc'))
  const scroller = page.locator('.foreground-layer.active .view-container')
  await scroller.evaluate(element => {
    element.dispatchEvent(new WheelEvent('wheel', { deltaY: -10000 }))
    element.scrollTop = 0
    element.dispatchEvent(new Event('scroll'))
  })
  expect(await scroller.evaluate(element => element.scrollHeight > element.clientHeight)).toBe(true)
  await online(page)
  await expect(page.getByRole('button', { name: 'Send', exact: true })).toBeEnabled()
  await expect(page.getByLabel('Message Hermes')).toHaveValue('A draft')
  await expect(page.getByText('Connected. Your draft has not been sent.', { exact: true })).toHaveCount(0)
  expect(await scroller.evaluate(element => element.scrollTop)).toBeLessThan(40)
  expect((await calls(page)).filter(call => call.method === 'prompt.submit')).toHaveLength(0)
  await expect(page.getByText('Durable reply from saved-default', { exact: true })).toHaveCount(1)
  await page.getByRole('button', { name: 'Send', exact: true }).click()
  await expect.poll(async () => (await calls(page)).filter(call => call.method === 'prompt.submit').length).toBe(1)
})

test('exhausted handshakes keep the workspace and Retry targets the newest cached selection', async ({ page }) => {
  test.setTimeout(60000)
  await login(page)
  await control(page, { rejectHandshake: true, closeSockets: true })
  await expect(page.locator('.connection-banner')).toContainText('Cannot reach Hermes.', { timeout: 30000 })
  await expect(page.getByLabel('Message Hermes')).toBeEditable()
  await page.getByLabel('Message Hermes').fill('after exhaustion')
  await control(page, { rejectHandshake: false, delayHistory: true })
  await page.getByRole('button', { name: 'Retry', exact: true }).click()
  await expect(page.locator('.connection-banner')).toContainText('Updating this conversation…')
  await expect(page.getByRole('button', { name: 'Send', exact: true })).toBeDisabled()
  await expect(page.getByText('Durable reply from saved-default', { exact: true })).toBeVisible()
  await control(page, { delayHistory: false })
  await expect(page.getByRole('button', { name: 'Send', exact: true })).toBeEnabled()
  expect((await calls(page)).filter(call => call.method === 'prompt.submit')).toHaveLength(0)
})

test('a missing cached target retains history and draft without creating a replacement', async ({ page }) => {
  await login(page)
  await page.getByLabel('Message Hermes').fill('not another session')
  await offline(page)
  await control(page, { missingSession: 'saved-default' })
  const before = (await calls(page)).filter(call => call.method === 'session.create').length
  await online(page)
  await expect(page.getByRole('button', { name: 'Retry', exact: true })).toBeVisible()
  await expect(page.getByText('Durable reply from saved-default', { exact: true })).toBeVisible()
  await expect(page.getByLabel('Message Hermes')).toHaveValue('not another session')
  await expect(page.getByRole('button', { name: 'Send', exact: true })).toBeDisabled()
  expect((await calls(page)).filter(call => call.method === 'session.create')).toHaveLength(before)
})

test('authentication expiry hides the private workspace', async ({ page }) => {
  await login(page)
  await page.getByLabel('Message Hermes').fill('private')
  await control(page, { authExpired: true, closeSockets: true })
  await expect(page.getByRole('button', { name: 'Continue' })).toBeVisible()
  await expect(page.getByLabel('Message Hermes')).toHaveCount(0)
  await expect(page.getByText('Durable reply from saved-default', { exact: true })).toHaveCount(0)
})

test('interruption settles pending delivery as uncertain, preserves newer typing, and never resends', async ({ page }) => {
  await login(page)
  await page.getByLabel('Message Hermes').fill('draft delayed failure')
  await page.getByRole('button', { name: 'Send', exact: true }).click()
  await expect.poll(async () => (await calls(page)).filter(call => call.method === 'prompt.submit').length).toBe(1)
  await control(page, { rejectHandshake: true, closeSockets: true })
  await page.getByLabel('Message Hermes').fill('My next question')
  await expect(page.locator('summary').getByText('Delivery not confirmed.', { exact: false })).toBeVisible()
  await control(page, { rejectHandshake: false })
  await online(page)
  await expect(page.getByRole('button', { name: 'Send', exact: true })).toBeEnabled()
  await expect(page.getByLabel('Message Hermes')).toHaveValue('My next question')
  expect((await calls(page)).filter(call => call.method === 'prompt.submit')).toHaveLength(1)
})

test('an open profile editor retains its values and Cancel during interruption', async ({ page }) => {
  await login(page)
  await page.getByRole('button', { name: 'Back to bots' }).click()
  await page.getByRole('button', { name: 'Create profile', exact: true }).click()
  await page.getByRole('button', { name: 'New bot', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: 'Create profile', exact: true })
  const input = dialog.locator('#create-profile-name')
  await input.fill('preserved-profile')
  await control(page, { serverFailure: true, closeSockets: true })
  await expect(dialog.getByRole('button', { name: 'Create profile', exact: true })).toBeDisabled()
  await expect(input).toHaveValue('preserved-profile')
  await dialog.getByRole('button', { name: 'Cancel', exact: true }).click()
  await expect(dialog).toHaveCount(0)
  expect((await calls(page)).filter(call => call.method === 'profiles.create')).toHaveLength(0)
})

test('server failure leaves local appearance and sign out usable', async ({ page }) => {
  await login(page)
  await page.getByLabel('Message Hermes').fill('private')
  await control(page, { serverFailure: true, closeSockets: true })
  await expect(page.locator('.connection-banner')).toContainText('Gateway unavailable.')
  await page.getByRole('button', { name: 'Back to bots' }).click()
  await page.getByRole('button', { name: 'Open settings' }).click()
  await page.getByRole('button', { name: /Appearance/ }).click()
  await page.getByRole('combobox').selectOption('dark')
  await page.getByRole('button', { name: 'Back', exact: true }).last().click()
  await page.getByRole('button', { name: 'Sign out', exact: true }).click()
  await page.getByRole('alertdialog').getByRole('button', { name: 'Sign out', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Continue' })).toBeVisible()
  expect(await page.evaluate(() => Object.keys(localStorage).filter(key => key.startsWith('hermes.transcript.v2:') || key.startsWith('hermes.drafts.v1:')))).toEqual([])
})
