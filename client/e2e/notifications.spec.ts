import { expect, test, type Page } from '@playwright/test'
async function login(page: Page) {
  await page.goto('/')
  await page.getByRole('button', { name: 'Continue' }).click()
  await page.getByRole('button', { name: 'Use password for Test account' }).click()
  await page.getByPlaceholder('Username').fill('notification-user')
  await page.getByPlaceholder('Password').fill('fixture-password')
  await page.getByRole('button', { name: 'Sign in', exact: true }).click()
  await page.getByRole('button', { name: 'Open settings' }).click()
  await page.getByRole('button', { name: /^Notifications / }).click()
  await expect(page.getByRole('heading', { name: 'Notifications', exact: true })).toBeVisible()
}
async function fixture(page: Page, values: Record<string, unknown>) { await page.evaluate(async values => { await fetch('/api/fixture-control', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify(values) }) }, values) }
async function mockPush(page: Page, permission = 'default') {
  await page.addInitScript(permission => {
    let subscribed = false
    const subscription = { endpoint: 'https://fcm.googleapis.com/fixture', expirationTime: null, toJSON: () => ({ endpoint: 'https://fcm.googleapis.com/fixture', expirationTime: null, keys: { auth: 'fixture', p256dh: 'fixture' } }), unsubscribe: async () => { subscribed = false; return true } }
    Object.defineProperty(window, 'PushManager', { configurable: true, value: class {} })
    const notification = { permission, requestPermission: async () => { notification.permission = 'granted'; return 'granted' } }
    Object.defineProperty(window, 'Notification', { configurable: true, value: notification })
    Object.defineProperty(navigator.serviceWorker, 'ready', { configurable: true, value: Promise.resolve({ pushManager: { getSubscription: async () => subscribed ? subscription : null, subscribe: async () => { subscribed = true; return subscription } } }) })
  }, permission)
}
test('separates setup facts, repairs registration, tests only this device and disables', async ({ page }, info) => {
  await page.setViewportSize({ width: 320, height: 700 })
  await mockPush(page)
  await login(page)
  await expect(page.getByText('Not registered for this account', { exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Send test notification', exact: true })).toBeDisabled()
  await page.getByRole('button', { name: 'Enable notifications', exact: true }).click()
  await expect(page.getByText('Registered for this account', { exact: true })).toBeVisible()
  await fixture(page, { pushFailure: true })
  await page.getByRole('button', { name: 'Refresh status' }).click()
  await expect(page.getByRole('alert')).toContainText('unavailable')
  await expect(page.getByText('Present on this device', { exact: true })).toBeVisible()
  await fixture(page, { pushFailure: false })
  await page.getByRole('button', { name: 'Refresh status' }).click()
  await expect(page.getByText('Registered for this account', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Send test notification', exact: true }).click()
  await expect(page.getByRole('region', { name: 'Test background notifications', exact: true }).getByRole('status')).toContainText('delivery is not confirmed')
  const calls = await page.evaluate(async () => (await (await fetch('/api/fixture-calls')).json()).calls)
  const sends = calls.filter((call: { path?: string }) => call.path === '/push/v1/test')
  expect(sends).toHaveLength(1)
  expect(Object.keys(sends[0].body).sort()).toEqual(['binding', 'requestId'])
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.evaluate(() => document.querySelectorAll('*').forEach(node => { if (node.scrollTop) node.scrollTop = 0 }))
  await page.screenshot({ path: info.outputPath('notifications-phone.png'), fullPage: true })
  await page.evaluate(() => { document.documentElement.classList.add('dark'); document.documentElement.classList.remove('light'); document.documentElement.dataset.theme = 'dark'; document.documentElement.style.fontSize = '20px' })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({ path: info.outputPath('notifications-large-dark.png'), fullPage: true })
  await page.getByRole('button', { name: 'Disable notifications', exact: true }).click()
  await expect(page.getByText('No local subscription', { exact: true })).toBeVisible()
})
test('blocked permission has guidance, passive refresh does not prompt, Back remains usable', async ({ page }) => {
  await mockPush(page, 'denied')
  await login(page)
  await expect(page.getByText(/Repeated permission requests cannot unblock/)).toBeVisible()
  await expect(page.getByRole('button', { name: 'Enable notifications', exact: true })).toBeDisabled()
  await page.getByRole('button', { name: 'Refresh status' }).click()
  await expect(page.getByText('Blocked', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Back', exact: true }).last().click()
  await expect(page.getByRole('heading', { name: 'Notifications', exact: true })).toHaveCount(0)
})
test('unsupported browser explains limitation without remote setup actions', async ({ page }) => {
  await page.addInitScript(() => { delete (window as unknown as { PushManager?: unknown }).PushManager })
  await login(page)
  await expect(page.getByText(/does not expose the required Web Push APIs/)).toBeVisible()
  await expect(page.getByRole('button', { name: 'Send test notification', exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: 'Back', exact: true }).last().click()
})

test('offline entry preserves Back and explains unverified registration', async ({ page, context }) => {
  await mockPush(page)
  await login(page)
  await expect(page.getByText('Not registered for this account', { exact: true })).toBeVisible()
  await context.setOffline(true)
  await expect(page.getByText('Could not verify while disconnected', { exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Enable notifications', exact: true })).toBeDisabled()
  await page.getByRole('button', { name: 'Back', exact: true }).last().click()
  await context.setOffline(false)
})

test('expired test gives recovery without reporting delivery', async ({ page }) => {
  await mockPush(page)
  await login(page)
  await page.getByRole('button', { name: 'Enable notifications', exact: true }).click()
  await expect(page.getByText('Registered for this account', { exact: true })).toBeVisible()
  await fixture(page, { pushExpired: true })
  await page.getByRole('button', { name: 'Send test notification', exact: true }).click()
  await expect(page.getByRole('region', { name: 'Test background notifications', exact: true }).getByRole('status')).toContainText('registration expired')
  await expect(page.getByText('Expired; disable then enable again', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Disable notifications', exact: true }).click()
  await fixture(page, { pushExpired: false })
  await page.getByRole('button', { name: 'Enable notifications', exact: true }).click()
  await expect(page.getByText('Registered for this account', { exact: true })).toBeVisible()
})
